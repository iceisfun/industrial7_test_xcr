/* gen_stb_refs.c - HOST tool (native Linux gcc): golden output hashes of the vendored stb_image JPEG decoder
 * (third_party/stb/stb_image.h, see tests/simd_jpeg_stb.h) for every simd_jpeg corpus and synthetic image.
 * stb's JPEG path is integer-only, so these hashes are a pure function of the input bytes; the simd_jpeg
 * exe recomputes them with stb's portable C and SSE2 kernels and must match exactly.
 *
 * It refuses to write the header unless stb's C and SSE2 kernels agree bit for bit on the host, and prints
 * the per-image difference to the suite decoder (islow + fancy, the djpeg default) on stderr for review.
 *
 * build + run (from the repo root):
 *   gcc -O2 -I tests -o /tmp/gen_stb_refs corpus/jpeg/gen_stb_refs.c && /tmp/gen_stb_refs > tests/simd_jpeg_stb_ref.h */
#include <stdio.h>
#include "simd_jpeg_dec.h"
#include "simd_jpeg_enc.h"
#include "simd_jpeg_corpus.h"
#include "simd_jpeg_stb.h"

#if !SJ_HAVE_STB || !SJ_STB_HAVE_SSE2
#error "stb_image with its SSE2 path is required"
#endif

typedef struct res { int ok, w, h, nc; uint64_t h_nat, h_rgba; int maxd; double mean; } res;

static int one(const char *name, const uint8_t *d, size_t n, int suite_ok, res *r) {
    memset(r, 0, sizeof *r);
    int w, h, nc, oc, w2, h2, nc2, oc2;
    uint8_t *a = sj_stb_decode(d, n, 0, 0, &w, &h, &nc, &oc);
    uint8_t *b = sj_stb_decode(d, n, 1, 0, &w2, &h2, &nc2, &oc2);
    if (!a != !b) { fprintf(stderr, "%s: stb C ok=%d SSE2 ok=%d\n", name, !!a, !!b); return 0; }
    if (!a) { fprintf(stderr, "%-24s stb rejects: %s\n", name, stbi_failure_reason()); return 1; }
    size_t sz = (size_t)w * h * oc;
    if (w != w2 || h != h2 || oc != oc2 || memcmp(a, b, sz)) { fprintf(stderr, "%s: stb C != SSE2 (native)\n", name); return 0; }
    r->ok = 1; r->w = w; r->h = h; r->nc = oc;
    r->h_nat = jd_fnv64(a, sz);
    uint8_t *c = sj_stb_decode(d, n, 0, 4, &w, &h, &nc, &oc), *e = sj_stb_decode(d, n, 1, 4, &w2, &h2, &nc2, &oc2);
    if (!c || !e || memcmp(c, e, (size_t)w * h * 4)) { fprintf(stderr, "%s: stb C != SSE2 (RGBA)\n", name); return 0; }
    r->h_rgba = jd_fnv64(c, (size_t)w * h * 4);
    if (suite_ok) {
        jd_options o; memset(&o, 0, sizeof o);
        o.max_pixels = 64u << 20;
        jd_image im;
        if (jd_decode(d, n, &o, &im) != JD_OK || im.w != w || im.h != h || im.ch != r->nc) {
            fprintf(stderr, "%s: suite decode differs in shape (%dx%dx%d vs stb %dx%dx%d)\n", name, im.w, im.h, im.ch, w, h, r->nc);
            return 0;
        }
        long double sum = 0;
        for (size_t i = 0; i < sz; i++) { int df = abs((int)im.pix[i] - (int)a[i]); if (df > r->maxd) r->maxd = df; sum += df; }
        r->mean = (double)(sum / sz);
        fprintf(stderr, "%-24s %5dx%-5d nc=%d max %2d mean %.4f\n", name, w, h, r->nc, r->maxd, r->mean);
        jd_free(&im);
    }
    stbi_image_free(a); stbi_image_free(b); stbi_image_free(c); stbi_image_free(e);
    return 1;
}

int main(void) {
    printf("/* generated by corpus/jpeg/gen_stb_refs.c - do not edit. Golden hashes (FNV-1a64 of the packed\n"
           " * pixels) of %s for the simd_jpeg corpus: native components (h_nat) and RGBA (h_rgba). */\n", SJ_STB_VERSION);
    printf("#ifndef SIMD_JPEG_STB_REF_H\n#define SIMD_JPEG_STB_REF_H\n");
    printf("typedef struct sj_stb_ref { const char *name; int ok, w, h, nc; uint64_t h_nat, h_rgba; int host_maxdiff; } sj_stb_ref;\n");
    printf("static const sj_stb_ref sj_stb_ref_list[] = {\n");
    int fails = 0, gmax = 0;
    res r;
    for (size_t i = 0; i < sizeof sj_corpus_list / sizeof sj_corpus_list[0]; i++) {
        const sj_corpus *c = &sj_corpus_list[i];
        /* corrupt / unsupported inputs are out of scope: stb's output for them is not even deterministic
         * (err_dht_oversub, markers_fill_96x72: stb then reads uninitialised memory) */
        if (c->expect != JD_OK || c->djpeg_rc != 0) continue;   /* clean files only */
        if (!one(c->name, c->data, c->len, c->expect == JD_OK, &r)) { fails++; continue; }
        if (r.maxd > gmax) gmax = r.maxd;
        printf("    { \"%s\", %d, %d, %d, %d, 0x%016llxull, 0x%016llxull, %d },\n", c->name, r.ok, r.w, r.h, r.nc,
               (unsigned long long)r.h_nat, (unsigned long long)r.h_rgba, r.maxd);
    }
    printf("};\nstatic const sj_stb_ref sj_stb_synth_ref_list[] = {\n");
    for (size_t i = 0; i < sizeof sj_synth_list / sizeof sj_synth_list[0]; i++) {
        const sj_synth *s = &sj_synth_list[i];
        uint8_t *rgb = malloc((size_t)s->w * s->h * 3);
        je_synth_rgb(rgb, s->w, s->h, s->seed);
        size_t n = 0;
        uint8_t *j = je_encode(rgb, s->w, s->h, s->sub, s->q, s->ri, &n);
        free(rgb);
        if (!j || n != s->jpeg_len || jd_fnv64(j, n) != s->jpeg_hash) { fprintf(stderr, "%s: encoder output differs\n", s->name); fails++; continue; }
        if (!one(s->name, j, n, 1, &r)) fails++;
        else {
            if (r.maxd > gmax) gmax = r.maxd;
            printf("    { \"%s\", %d, %d, %d, %d, 0x%016llxull, 0x%016llxull, %d },\n", s->name, r.ok, r.w, r.h, r.nc,
                   (unsigned long long)r.h_nat, (unsigned long long)r.h_rgba, r.maxd);
        }
        free(j);
    }
    printf("};\n#define SJ_STB_HOST_MAXDIFF %d\n#endif\n", gmax);
    fprintf(stderr, "max difference to the suite decoder over all images: %d; stb asserts: %ld\n", gmax, sj_stb_assert_count);
    return fails || sj_stb_assert_count ? 1 : 0;
}

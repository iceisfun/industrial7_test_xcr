typedef struct sj_bench { const uint8_t *d; size_t n; const jd_kernels *k; int dct, fmt; uint64_t want; int bad; } sj_bench;
static void sj_bench_decode(void *p) {
    sj_bench *b = (sj_bench *)p;
    jd_image im;
    if (sj_dec(b->d, b->n, b->k, b->dct, JD_UP_FANCY, b->fmt, &im) != JD_OK || (b->want && sj_hash(&im) != b->want)) b->bad++;
    T_SINK(im.pix ? im.pix[im.stride] : 0);
    jd_free(&im);
}
static void sj_perf_decode(int kidx, int dct) {
    const jd_kernels *k = sj_kernel_or_skip(kidx);
    const sj_synth *s; size_t n;
    const uint8_t *j = sj_synth_get("synth_4k_420", &n, &s);
    sj_bench b = { j, n, k, dct, JD_OUT_RGB, dct == JD_DCT_ISLOW ? s->h_int : 0, 0 };
    sj_bench_decode(&b);                  /* verify before timing */
    REQUIREF(b.bad == 0, "decode result wrong: refusing to report a number");
    b.want = 0;
    t_stats st;
    int got = t_bench(sj_bench_decode, &b, 1, 5, 0.0, &st);
    CHECK(got == 5 && b.bad == 0);
    char m[64];
    snprintf(m, sizeof m, "decode_4k_420_%s_%s", dct ? "float" : "islow", k->name);
    t_perf(m, (double)s->w * s->h / 1e6 / st.median, "MPix/s");
    t_info("median_ms", "%.1f (min %.1f max %.1f)", st.median * 1e3, st.min * 1e3, st.max * 1e3);
}

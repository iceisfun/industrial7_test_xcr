/* every prefix length of small files: never crash / over-read; error before the first scan, documented
 * partial output after; complete output once only EOI is missing; kernels agree */
static void sj_every_prefix(const char *img) {
    const sj_corpus *c = sj_find(img);
    REQUIRE(c);
    const jd_kernels *ks[3]; int nk = sj_usable(ks);
    int nerr = 0, nok = 0, nmis = 0;
    for (uint32_t L = 0; L <= c->len; L++) {
        void *base;
        uint8_t *d = (uint8_t *)t_guarded_alloc(L ? L : 1, &base);
        REQUIRE(d);
        memcpy(d, c->data, L);
        uint64_t h0 = 0; int rc0 = 0;
        for (int k = 0; k < nk; k++) {
            jd_image im;
            int rc = sj_dec(d, L, ks[k], JD_DCT_ISLOW, JD_UP_FANCY, JD_OUT_NATIVE, &im);
            uint64_t h = sj_hash(&im);
            if (rc == JD_OK) {
                if (im.w != c->w || im.h != c->h) CHECKF(0, "len %u: %dx%d", L, im.w, im.h);
                if (L >= c->len - 2) CHECKF(h == c->h_int, "%s len %u (EOI missing at most): output must be complete", ks[k]->name, L);
                else if (!(im.warnings & (JD_W_EOF | JD_W_TRUNCATED | JD_W_PARTIAL_HDR))) CHECKF(0, "%s len %u: no truncation warning", ks[k]->name, L);
            }
            if (k == 0) { h0 = h; rc0 = rc; if (rc) nerr++; else nok++; }
            else if (h != h0 || rc != rc0) nmis++;
            jd_free(&im);
        }
        t_guarded_free(base);
    }
    t_info("prefixes", "%u: %d error, %d decoded", c->len + 1, nerr, nok);
    CHECKF(nmis == 0, "%d prefixes decoded differently by some kernel set", nmis);
    CHECK(nok > 0 && nerr > 0);
}

/* simd_jpeg - real-world SIMD workload: a self-contained baseline + progressive JPEG decoder
 * (tests/simd_jpeg_dec.h) with scalar / SSE2 / AVX2 kernels for the islow integer IDCT, the AAN float
 * IDCT, fancy upsampling (h2v1, h2v2, h1v2) and YCbCr->RGB/RGBA conversion.
 *
 * What is checked (wrong pixels are a FAIL):
 *  - every kernel set is bit-identical to the scalar one (seeded random, extreme and exhaustive inputs);
 *  - scalar kernels against closed forms / independent re-implementations and golden hashes computed
 *    on the corpus host from the same source (integer arithmetic and IEEE single precision with a fixed
 *    operation order are exact, so any correct x86 CPU + OS reproduces them);
 *  - IDCT accuracy against a double-precision IDCT with the IEEE 1180-1990 limits;
 *  - decoded images against libjpeg-turbo djpeg (an independent decoder) via pixel hashes stored in
 *    tests/simd_jpeg_corpus.h / corpus/reference_vectors (generated by corpus/jpeg/gen_corpus.py):
 *    exact match required for `-dct int` (fancy upsampling) and `-nosmooth` (box upsampling);
 *    for truncated baseline files djpeg's documented partial output (grey blocks) is reproduced exactly;
 *  - corrupt / mutated input: clean error or documented partial output, never a crash, never an
 *    out-of-bounds read (inputs sit right before a PAGE_NOACCESS page), identical results per kernel;
 *  - many threads decoding the same image concurrently with different kernel sets: identical results;
 *  - the decoder neither depends on nor modifies the FP environment where the architecture says so.
 * PERF: MPixel/s per kernel set (4K decode) and kernel micro-benchmarks.
 * x86 (32-bit) builds run everything; there is nothing x64-only here except more XMM registers. */
#include "t.h"
#include <math.h>
#include "simd_jpeg_dec.h"
#include "simd_jpeg_enc.h"
#include "simd_jpeg_corpus.h"

/* ============================================================================================ */
/* helpers                                                                                       */

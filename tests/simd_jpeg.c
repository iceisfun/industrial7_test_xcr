TEST(fpenv_decode_preserves_mxcsr_and_x87) {
    const jd_kernels *ks[3]; int nk = sj_usable(ks);
    const sj_corpus *c = sj_find("c420_96x72");
    unsigned m0 = t_get_mxcsr() & ~0x3Fu;
    unsigned cw0 = t_get_x87_cw();
    for (int k = 0; k < nk; k++)
        for (int f = 0; f < 2; f++) {
            t_set_mxcsr(m0);
            jd_image im;
            CHECK(sj_dec(c->data, c->len, ks[k], f, JD_UP_FANCY, JD_OUT_RGBA, &im) == JD_OK);
            jd_free(&im);
            unsigned m1 = t_get_mxcsr();
            CHECKF((m1 & ~0x3Fu) == m0, "%s %s: MXCSR control 0x%x -> 0x%x", ks[k]->name, f ? "float" : "islow", m0, m1);
            CHECKF(t_get_x87_cw() == cw0, "%s: x87 CW changed 0x%x -> 0x%x", ks[k]->name, cw0, t_get_x87_cw());
        }
}
/* the integer path cannot depend on MXCSR; the float path cannot see denormals (all nonzero
 * intermediates are >= ~1e-9 in magnitude), so FTZ/DAZ must not change it either */
TEST(fpenv_results_independent_of_ftz_daz_rc) {
    const jd_kernels *ks[3]; int nk = sj_usable(ks);
    const sj_corpus *c = sj_find("prog_custom_96x72");
    unsigned m0 = t_get_mxcsr();
    uint64_t hf[3] = { 0 };
    for (int k = 0; k < nk; k++) {
        jd_image im;
        REQUIRE(sj_dec(c->data, c->len, ks[k], JD_DCT_FLOAT, JD_UP_FANCY, JD_OUT_RGB, &im) == JD_OK);
        hf[k] = sj_hash(&im); jd_free(&im);
    }
    static const unsigned modes[] = { 0x8040 /* FTZ|DAZ */, 0x6000 /* RC toward zero */, 0x2000 /* RC down */, 0x4000 /* RC up */ };
    for (size_t mi = 0; mi < T_COUNTOF(modes); mi++)
        for (int k = 0; k < nk; k++) {
            jd_image im;
            t_set_mxcsr((m0 & ~0xE040u) | modes[mi]);
            int rc = sj_dec(c->data, c->len, ks[k], JD_DCT_ISLOW, JD_UP_FANCY, JD_OUT_RGB, &im);
            uint64_t hi = sj_hash(&im); jd_free(&im);
            int rc2 = sj_dec(c->data, c->len, ks[k], JD_DCT_FLOAT, JD_UP_FANCY, JD_OUT_RGB, &im);
            uint64_t h2 = sj_hash(&im); jd_free(&im);
            t_set_mxcsr(m0);
            CHECKF(rc == 0 && hi == c->h_int, "%s islow under MXCSR 0x%x differs", ks[k]->name, modes[mi]);
            CHECK(rc2 == 0);
            if (modes[mi] == 0x8040) CHECKF(h2 == hf[k], "%s float under FTZ|DAZ differs", ks[k]->name);
            else if (k == 0) t_info(modes[mi] == 0x6000 ? "float_rc_zero" : modes[mi] == 0x2000 ? "float_rc_down" : "float_rc_up",
                                    "%s", h2 == hf[k] ? "same pixels" : "different pixels (expected: float IDCT rounds per MXCSR.RC)");
            if (k > 0 && rc2 == 0) {
                /* whatever the rounding mode, every kernel set rounds the same IEEE operations */
                jd_image a;
                t_set_mxcsr((m0 & ~0xE040u) | modes[mi]);
                sj_dec(c->data, c->len, ks[0], JD_DCT_FLOAT, JD_UP_FANCY, JD_OUT_RGB, &a);
                t_set_mxcsr(m0);
                CHECKF(sj_hash(&a) == h2, "%s vs scalar float differ under MXCSR 0x%x", ks[k]->name, modes[mi]);
                jd_free(&a);
            }
        }
}
/* the scalar float kernel uses SSE arithmetic, so x87 precision control cannot affect it */
TEST(fpenv_float_independent_of_x87_precision) {
    const sj_corpus *c = sj_find("c420_96x72");
    jd_image im;
    REQUIRE(sj_dec(c->data, c->len, NULL, JD_DCT_FLOAT, JD_UP_FANCY, JD_OUT_RGB, &im) == JD_OK);
    uint64_t h0 = sj_hash(&im); jd_free(&im);
    unsigned cw = t_get_x87_cw();
    static const unsigned pc[] = { 0x000 /* 24-bit */, 0x200 /* 53-bit */, 0x300 /* 64-bit */ };
    for (size_t i = 0; i < T_COUNTOF(pc); i++) {
        t_set_x87_cw((cw & ~0x300u) | pc[i]);
        int rc = sj_dec(c->data, c->len, NULL, JD_DCT_FLOAT, JD_UP_FANCY, JD_OUT_RGB, &im);
        t_set_x87_cw(cw);
        CHECKF(rc == 0 && sj_hash(&im) == h0, "x87 PC 0x%x changed the float decode", pc[i]);
        jd_free(&im);
    }
}


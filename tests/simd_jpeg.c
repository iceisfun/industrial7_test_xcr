typedef struct sj_synth_img { uint8_t *jpg; size_t len; int state; } sj_synth_img;
static sj_synth_img g_synth[8];
static const uint8_t *sj_synth_get(const char *name, size_t *len, const sj_synth **sp) {
    const sj_synth *s = sj_find_synth(name);
    REQUIREF(s != NULL, "synthetic %s missing", name);
    int idx = (int)(s - sj_synth_list);
    sj_synth_img *g = &g_synth[idx];
    if (!g->state) {
        uint8_t *rgb = (uint8_t *)malloc((size_t)s->w * s->h * 3);
        if (!rgb) SKIP("%s: no memory for the %dx%d source image", name, s->w, s->h);   /* retried next time */
        je_synth_rgb(rgb, s->w, s->h, s->seed);
        g->jpg = je_encode(rgb, s->w, s->h, s->sub, s->q, s->ri, &g->len);
        free(rgb);
        if (!g->jpg) SKIP("%s: encoder out of memory", name);
        g->state = 1;
    }
    *len = g->len;
    if (sp) *sp = s;
    return g->jpg;
}
TEST(synth_encoder_deterministic) {
    for (size_t i = 0; i < T_COUNTOF(sj_synth_list); i++) {
        const sj_synth *s = &sj_synth_list[i];
        size_t n;
        if ((uint64_t)s->w * s->h > (16u << 20)) continue;   /* > default max_pixels: own case (synth_8k_*) */
        double t0 = t_now_ms();
        const uint8_t *j = sj_synth_get(s->name, &n, NULL);
        t_info(s->name, "%dx%d %u bytes, encoded in %.0f ms", s->w, s->h, (unsigned)n, t_now_ms() - t0);
        CHECKF(n == s->jpeg_len, "%s: %u bytes, host produced %u", s->name, (unsigned)n, s->jpeg_len);
        CHECKF(jd_fnv64(j, n) == s->jpeg_hash, "%s: JPEG bytes differ from the host encoding", s->name);
    }
}
static void sj_synth_decode(const char *name, int kidx, int reps) {
    const jd_kernels *k = sj_kernel_or_skip(kidx);
    const sj_synth *s;
    size_t n;
    const uint8_t *j = sj_synth_get(name, &n, &s);
    for (int r = 0; r < reps; r++) {
        jd_image im;
        int rc = sj_dec(j, n, k, JD_DCT_ISLOW, (r & 1) ? JD_UP_BOX : JD_UP_FANCY, JD_OUT_NATIVE, &im);
        REQUIREF(rc == JD_OK, "%s rc %d (%s)", name, rc, sj_err(rc));
        uint64_t h = sj_hash(&im), want = (r & 1) ? s->h_box : s->h_int;
        CHECKF(h == want, "%s %s rep %d (%s): hash %016llx want djpeg %016llx", name, k->name, r, (r & 1) ? "box" : "fancy",
               (unsigned long long)h, (unsigned long long)want);
        CHECK_EQ(im.warnings, 0);
        jd_free(&im);
    }
}

static void sj_trunc_family(const char *img) {
    const jd_kernels *ks[3]; int nk = sj_usable(ks);
    int seen = 0;
    for (size_t i = 0; i < T_COUNTOF(sj_trunc_list); i++) {
        const sj_trunc *t = &sj_trunc_list[i];
        if (strcmp(t->img, img)) continue;
        const sj_corpus *c = sj_find(img);
        REQUIRE(c && t->len <= c->len);
        seen++;
        /* exact-length copy so any read past the end faults */
        void *base;
        uint8_t *d = (uint8_t *)t_guarded_alloc(t->len ? t->len : 1, &base);
        REQUIRE(d);
        memcpy(d, c->data, t->len);
        uint64_t h0 = 0; int rc0 = 0, w0 = 0;
        for (int k = 0; k < nk; k++) {
            jd_image im;
            int rc = sj_dec(d, t->len, ks[k], JD_DCT_ISLOW, JD_UP_FANCY, JD_OUT_NATIVE, &im);
            uint64_t h = sj_hash(&im);
            if (k == 0) {
                char key[48]; snprintf(key, sizeof key, "len_%u", t->len);
                t_info(key, "rc %d warn 0x%x mcus %u/%u", rc, im.warnings, im.mcus_decoded, im.mcus_total);
            }
            if (!t->djpeg_ok) CHECKF(rc < 0, "%s len %u: djpeg fails (header incomplete) but rc %d", ks[k]->name, t->len, rc);
            else {
                CHECKF(rc == JD_OK, "%s len %u: rc %d (%s), want partial output", ks[k]->name, t->len, rc, sj_err(rc));
                if (rc == JD_OK) {
                    CHECKF(im.warnings & (JD_W_EOF | JD_W_TRUNCATED), "%s len %u: truncated input without warning", ks[k]->name, t->len);
                    if (t->compare)
                        CHECKF(h == t->h_int, "%s len %u: partial output differs from djpeg (hash %016llx want %016llx)", ks[k]->name, t->len,
                               (unsigned long long)h, (unsigned long long)t->h_int);
                }
            }
            if (k == 0) { h0 = h; rc0 = rc; w0 = im.warnings; }
            else CHECKF(h == h0 && rc == rc0 && im.warnings == w0, "%s len %u: result differs from scalar", ks[k]->name, t->len);
            jd_free(&im);
        }
        t_guarded_free(base);
    }
    REQUIREF(seen > 0, "no truncation vectors for %s", img);
}

/* jdcolor.c build_ycc_rgb_table(), re-implemented independently with tables */
static int g_crr[256], g_cbb[256], g_crg[256], g_cbg[256];
static void sj_ycc_tables(void) {
#define SJ_FIX(x) ((int)((x) * 65536.0 + 0.5))
    for (int i = 0; i < 256; i++) {
        int x = i - 128;
        g_crr[i] = (SJ_FIX(1.40200) * x + 32768) >> 16;
        g_cbb[i] = (SJ_FIX(1.77200) * x + 32768) >> 16;
        g_crg[i] = -SJ_FIX(0.71414) * x;
        g_cbg[i] = -SJ_FIX(0.34414) * x + 32768;
    }
#undef SJ_FIX
}
static uint8_t sj_cl(int v) { return (uint8_t)(v < 0 ? 0 : v > 255 ? 255 : v); }
/* all 2^24 (Y,Cb,Cr): kernel == table reference */
static void sj_ycc_exhaustive(int idx, int rgba) {
    const jd_kernels *k = sj_kernel_or_skip(idx);
    sj_ycc_tables();
    static uint8_t Y[256], U[256], V[256], o[1024], r[1024];
    int ch = rgba ? 4 : 3;
    long bad = 0;
    for (int y = 0; y < 256; y++) Y[y] = (uint8_t)y;
    for (int cb = 0; cb < 256; cb++)
        for (int cr = 0; cr < 256; cr++) {
            memset(U, cb, 256); memset(V, cr, 256);
            for (int y = 0; y < 256; y++) {
                r[ch * y] = sj_cl(y + g_crr[cr]);
                r[ch * y + 1] = sj_cl(y + ((g_cbg[cb] + g_crg[cr]) >> 16));
                r[ch * y + 2] = sj_cl(y + g_cbb[cb]);
                if (rgba) r[4 * y + 3] = 255;
            }
            if (rgba) k->ycc_rgba(Y, U, V, o, 256); else k->ycc_rgb(Y, U, V, o, 256);
            if (memcmp(o, r, (size_t)(256 * ch))) {
                if (bad++ < 2) { t_note("%s cb=%d cr=%d", k->name, cb, cr); CHECK_MEM(o, r, (size_t)(256 * ch)); }
            }
        }
    CHECKF(bad == 0, "%s %s: %ld of 65536 (Cb,Cr) rows differ from jdcolor.c arithmetic", k->name, rgba ? "RGBA" : "RGB", bad);
}
TEST(ycc_rgb_exhaustive_scalar)  { sj_ycc_exhaustive(0, 0); }

typedef struct sj_kset { const jd_kernels *k; int usable; const char *why; } sj_kset;
static sj_kset g_ks[3];
static int sj_ksets(void) {
    g_ks[0].k = &jd_kernels_scalar; g_ks[0].usable = 1; g_ks[0].why = "";
    g_ks[1].k = &jd_kernels_sse2; g_ks[1].usable = cpu_has(F_SSE2); g_ks[1].why = "SSE2 not usable";
    g_ks[2].k = &jd_kernels_avx2; g_ks[2].usable = cpu_has(F_AVX2); g_ks[2].why = "AVX2 not usable (CPUID bit or XCR0 YMM state missing)";
    return 3;
}
/* usable kernel sets in a compact list (scalar first) */
static int sj_usable(const jd_kernels **out) {
    int n = 0;
    sj_ksets();
    for (int i = 0; i < 3; i++) if (g_ks[i].usable) out[n++] = g_ks[i].k;
    return n;
}
static const jd_kernels *sj_kernel_or_skip(int idx) {
    sj_ksets();
    if (!g_ks[idx].usable) SKIP("%s", g_ks[idx].why);
    return g_ks[idx].k;
}
static const sj_corpus *sj_find(const char *name) {
    for (size_t i = 0; i < T_COUNTOF(sj_corpus_list); i++)
        if (!strcmp(sj_corpus_list[i].name, name)) return &sj_corpus_list[i];
    return NULL;
}
static const sj_synth *sj_find_synth(const char *name) {
    for (size_t i = 0; i < T_COUNTOF(sj_synth_list); i++)
        if (!strcmp(sj_synth_list[i].name, name)) return &sj_synth_list[i];
    return NULL;
}
static int sj_dec(const uint8_t *d, size_t n, const jd_kernels *k, int dct, int up, int fmt, jd_image *im) {
    jd_options o;
    memset(&o, 0, sizeof o);
    o.k = k; o.dct = dct; o.upsample = up; o.out_fmt = fmt;
    return jd_decode(d, n, &o, im);
}
static uint64_t sj_hash(const jd_image *im) { return im->pix ? jd_fnv64(im->pix, im->stride * (size_t)im->h) : 0; }
static uint64_t sj_fnv_upd(uint64_t h, const void *p, size_t n) {
    const uint8_t *b = (const uint8_t *)p;
    for (size_t i = 0; i < n; i++) { h ^= b[i]; h *= 0x100000001b3ull; }
    return h;
}
/* max |a-b| over n bytes, first index of the maximum */
static int sj_maxdiff(const uint8_t *a, const uint8_t *b, size_t n, size_t *at) {
    int m = 0;
    for (size_t i = 0; i < n; i++) {
        int d = a[i] > b[i] ? a[i] - b[i] : b[i] - a[i];
        if (d > m) { m = d; if (at) *at = i; }
    }
    return m;
}
static const char *sj_err(int rc) { return jd_strerror(rc); }


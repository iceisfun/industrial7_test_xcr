/* independent per-sample references (neighbour index clamped at the edges reproduces libjpeg's
 * special-cased first/last columns exactly) */
static void sj_ref_h2v1(const uint8_t *in, int w, uint8_t *out) {
    for (int x = 0; x < 2 * w; x++) {
        int i = x / 2;
        out[x] = (x & 1) ? (uint8_t)((3 * in[i] + in[i + 1 < w ? i + 1 : w - 1] + 2) >> 2)
                         : (uint8_t)((3 * in[i] + in[i > 0 ? i - 1 : 0] + 1) >> 2);
    }
}
static void sj_ref_h2v2(const uint8_t *a, const uint8_t *b, int w, uint8_t *out) {
    for (int x = 0; x < 2 * w; x++) {
        int i = x / 2, j = (x & 1) ? (i + 1 < w ? i + 1 : w - 1) : (i > 0 ? i - 1 : 0);
        int cs = 3 * a[i] + b[i], ns = 3 * a[j] + b[j];
        out[x] = (uint8_t)((3 * cs + ns + ((x & 1) ? 7 : 8)) >> 4);
    }
}
static void sj_ref_h1v2(const uint8_t *a, const uint8_t *b, int w, uint8_t *out, int lower) {
    for (int x = 0; x < w; x++) out[x] = (uint8_t)((3 * a[x] + b[x] + (lower ? 2 : 1)) >> 2);
}
enum { SJ_UP_H2V1, SJ_UP_H2V2, SJ_UP_H1V2 };
static void sj_up_call(const jd_kernels *k, int which, const uint8_t *a, const uint8_t *b, int w, uint8_t *o, int lower) {
    if (which == SJ_UP_H2V1) k->h2v1_fancy(a, w, o);
    else if (which == SJ_UP_H2V2) k->h2v2_fancy(a, b, w, o);
    else k->h1v2_fancy(a, b, w, o, lower);
}
static void sj_up_ref(int which, const uint8_t *a, const uint8_t *b, int w, uint8_t *o, int lower) {
    if (which == SJ_UP_H2V1) sj_ref_h2v1(a, w, o);
    else if (which == SJ_UP_H2V2) sj_ref_h2v2(a, b, w, o);
    else sj_ref_h1v2(a, b, w, o, lower);
}
static void sj_up_random(int which) {
    const jd_kernels *ks[3]; int nk = sj_usable(ks);
    static uint8_t a[1100], b[1100], o[2300], r[2300];
    uint64_t s = 0x0F00 + (uint64_t)which;
    int bad[3] = { 0 }, iters = 3000;
    for (int it = 0; it < iters; it++) {
        int w = 2 + (int)(sjv_next(&s) % (it < 400 ? 40 : 1000));
        int mode = it % 4;   /* random, extremes 0/255, constant, ramps */
        for (int i = 0; i < w; i++) {
            uint64_t v = sjv_next(&s);
            a[i] = mode == 0 ? (uint8_t)v : mode == 1 ? ((v & 1) ? 255 : 0) : mode == 2 ? 200 : (uint8_t)(i * 37);
            b[i] = mode == 0 ? (uint8_t)(v >> 8) : mode == 1 ? ((v & 2) ? 255 : 0) : mode == 2 ? 200 : (uint8_t)(255 - i * 11);
        }
        int lower = it & 1, on = which == SJ_UP_H1V2 ? w : 2 * w;
        sj_up_ref(which, a, b, w, r, lower);
        for (int k = 0; k < nk; k++) {
            memset(o, 0xEE, (size_t)on + 32);
            sj_up_call(ks[k], which, a, b, w, o, lower);
            if (memcmp(o, r, (size_t)on)) { if (bad[k]++ < 2) { t_note("%s w=%d lower=%d", ks[k]->name, w, lower); CHECK_MEM(o, r, (size_t)on); } }
            for (int i = on; i < on + 32; i++) if (o[i] != 0xEE) { CHECKF(0, "%s wrote past %d output samples (w=%d)", ks[k]->name, on, w); break; }
        }
    }
    for (int k = 0; k < nk; k++) CHECKF(bad[k] == 0, "%s: %d of %d rows differ from the reference formula", ks[k]->name, bad[k], iters);
}
TEST(upsample_h2v1_fancy_vs_reference) { sj_up_random(SJ_UP_H2V1); }
TEST(upsample_h2v2_fancy_vs_reference) { sj_up_random(SJ_UP_H2V2); }
TEST(upsample_h1v2_fancy_vs_reference) { sj_up_random(SJ_UP_H1V2); }

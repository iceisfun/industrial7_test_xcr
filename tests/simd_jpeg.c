static const char *const g_fuzz_bases[] = {
    "c420_96x72", "prog_custom_96x72", "c420_rst1b_96x72", "c444_rst5b_96x72", "gray_rst2b_96x72", "prog_rst_96x72",
    "seq_scans_96x72", "c420_17x13", "cinv_96x72", "c411_96x72", "c440_96x72", "c420_opt_96x72", "prog_gray_96x72" };
typedef struct sj_fuzz_stats { int n, ok, warn, err, mismatch; uint64_t agg; } sj_fuzz_stats;
/* deterministic mutation of base into out (cap >= blen + 64); returns new length */
static size_t sj_mutate(const uint8_t *base, size_t blen, uint64_t *s, uint8_t *out) {
    size_t n = blen;
    memcpy(out, base, n);
    int op = (int)(sjv_next(s) % 10);
    size_t pos = (size_t)(sjv_next(s) % n);
    switch (op) {
    case 0: out[pos] ^= (uint8_t)(1u << (sjv_next(s) & 7)); break;
    case 1: for (int i = 0, m = 1 + (int)(sjv_next(s) % 8); i < m; i++) out[sjv_next(s) % n] ^= (uint8_t)(1u << (sjv_next(s) & 7)); break;
    case 2: out[pos] = (uint8_t)sjv_next(s); break;
    case 3: out[pos] = 0xFF; break;
    case 4: {
        static const uint8_t mk[] = { 0xD0, 0xD3, 0xD7, 0xD9, 0xC4, 0xDA, 0xDB, 0xDD, 0xC0, 0xC2, 0xD8, 0x01, 0xFE };
        memmove(out + pos + 2, out + pos, n - pos);
        out[pos] = 0xFF; out[pos + 1] = mk[sjv_next(s) % sizeof mk]; n += 2;
        break;
    }
    case 5: { size_t k = 1 + (size_t)(sjv_next(s) % 32); if (pos + k > n) k = n - pos; memmove(out + pos, out + pos + k, n - pos - k); n -= k; break; }
    case 6: { size_t k = 1 + (size_t)(sjv_next(s) % 60); if (pos + k > n) k = n - pos; memmove(out + pos + k, out + pos, n - pos); n += k; break; }
    case 7: n = 2 + (size_t)(sjv_next(s) % (blen - 1)); break;
    case 8: for (int i = 0, m = 1 + (int)(sjv_next(s) % 3); i < m; i++) out[sjv_next(s) % (n < 700 ? n : 700)] = (uint8_t)sjv_next(s); break;
    default: { size_t k = 1 + (size_t)(sjv_next(s) % 16); if (pos + k > n) k = n - pos; memset(out + pos, 0, k); break; }
    }
    if (n < 1) n = 1;
    return n;
}
/* one mutation, decoded by every usable kernel set from a buffer that ends at a guard page */
static void sj_fuzz_one(const jd_kernels *const *ks, int nk, const uint8_t *base, size_t blen, uint64_t seed, sj_fuzz_stats *st) {
    static uint8_t buf[16384];
    uint64_t s = seed;
    size_t n = sj_mutate(base, blen, &s, buf);
    void *gb;
    uint8_t *d = (uint8_t *)t_guarded_alloc(n, &gb);
    if (!d) return;
    memcpy(d, buf, n);
    jd_options o; memset(&o, 0, sizeof o);
    o.max_pixels = 1u << 20;
    o.dct = (int)(seed & 1);
    uint64_t h0 = 0; int rc0 = 0, w0 = 0;
    for (int k = 0; k < nk; k++) {
        jd_image im;
        o.k = ks[k];
        int rc = jd_decode(d, n, &o, &im);
        uint64_t h = sj_hash(&im);
        if (k == 0) {
            h0 = h; rc0 = rc; w0 = im.warnings;
            if (rc) st->err++; else if (im.warnings) st->warn++; else st->ok++;
        } else if (h != h0 || rc != rc0 || im.warnings != w0) st->mismatch++;
        jd_free(&im);
    }
    uint64_t rec[3] = { (uint64_t)(int64_t)rc0, (uint64_t)w0, h0 };
    st->agg = sj_fnv_upd(st->agg, rec, sizeof rec);
    st->n++;
    t_guarded_free(gb);
}
static void sj_fuzz_run(uint64_t seed, int count, int first_base, int nbases, sj_fuzz_stats *st) {
    const jd_kernels *ks[3]; int nk = sj_usable(ks);
    memset(st, 0, sizeof *st);
    st->agg = 0xcbf29ce484222325ull;
    for (int i = 0; i < count; i++) {
        const sj_corpus *c = sj_find(g_fuzz_bases[first_base + i % nbases]);
        if (!c) continue;
        sj_fuzz_one(ks, nk, c->data, c->len, seed * 1000003u + (uint64_t)i, st);
    }
}
static void sj_fuzz_case(uint64_t seed, int count, int first, int nb) {
    sj_fuzz_stats a, b;
    double t0 = t_now_ms();
    sj_fuzz_run(seed, count, first, nb, &a);
    t_info("mutations", "%d: %d clean, %d with warnings, %d errors", a.n, a.ok, a.warn, a.err);
    t_info("ms", "%.0f", t_now_ms() - t0);
    CHECKF(a.mismatch == 0, "%d mutations decoded differently by some kernel set", a.mismatch);
    CHECK_EQ(a.n, count);
    /* determinism: the same mutations again give the same results */
    sj_fuzz_run(seed, count < 120 ? count : 120, first, nb, &b);
    sj_fuzz_stats c;
    sj_fuzz_run(seed, count < 120 ? count : 120, first, nb, &c);
    CHECKF(b.agg == c.agg, "fuzz results not deterministic");
}
TEST(fuzz_baseline_mutations)    { sj_fuzz_case(1, 300, 0, 1); }
TEST(fuzz_progressive_mutations) { sj_fuzz_case(2, 300, 1, 1); }
TEST(fuzz_restart_mutations)     { sj_fuzz_case(3, 300, 2, 4); }
TEST(fuzz_mixed_mutations)       { sj_fuzz_case(4, 300, 6, 7); }


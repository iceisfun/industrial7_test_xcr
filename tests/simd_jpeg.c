typedef struct sj_synth_img { uint8_t *jpg; size_t len; int state; } sj_synth_img;
static sj_synth_img g_synth[8];
static const uint8_t *sj_synth_get(const char *name, size_t *len, const sj_synth **sp) {
    const sj_synth *s = sj_find_synth(name);
    REQUIREF(s != NULL, "synthetic %s missing", name);
    int idx = (int)(s - sj_synth_list);
    sj_synth_img *g = &g_synth[idx];
    if (!g->state) {
        uint8_t *rgb = (uint8_t *)malloc((size_t)s->w * s->h * 3);
        REQUIRE(rgb);
        je_synth_rgb(rgb, s->w, s->h, s->seed);
        g->jpg = je_encode(rgb, s->w, s->h, s->sub, s->q, s->ri, &g->len);
        free(rgb);
        g->state = g->jpg ? 1 : -1;
    }
    REQUIREF(g->state == 1, "encoding %s failed (out of memory)", name);
    *len = g->len;
    if (sp) *sp = s;
    return g->jpg;
}
